/**
 * Translate a key. Supports {var} interpolation.
 * Falls back to key itself if translation not found.
 */
export function t(key, vars = {}) {
  const dict = TRANSLATIONS[_locale] || TRANSLATIONS.en;
  let str = dict[key];
  if (str === undefined) {
    // try English fallback
    str = TRANSLATIONS.en[key];
  }
  if (str === undefined) return key;
  return str.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] !== undefined ? vars[name] : `{${name}}`
  );
}
